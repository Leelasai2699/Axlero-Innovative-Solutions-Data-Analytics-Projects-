-- Metric Mind: Snowflake warehouse and raw landing layer.
-- Upload the four CSVs to @METRIC_MIND.RAW.CSV_STAGE before running the COPY commands.

CREATE WAREHOUSE IF NOT EXISTS METRIC_MIND_WH
    WAREHOUSE_SIZE = 'XSMALL'
    AUTO_SUSPEND = 60
    AUTO_RESUME = TRUE
    INITIALLY_SUSPENDED = TRUE;

CREATE DATABASE IF NOT EXISTS METRIC_MIND;
CREATE SCHEMA IF NOT EXISTS METRIC_MIND.RAW;

USE WAREHOUSE METRIC_MIND_WH;
USE DATABASE METRIC_MIND;
USE SCHEMA RAW;

CREATE FILE FORMAT IF NOT EXISTS CSV_STANDARD_FORMAT
    TYPE = CSV
    SKIP_HEADER = 1
    FIELD_OPTIONALLY_ENCLOSED_BY = '"'
    EMPTY_FIELD_AS_NULL = TRUE
    NULL_IF = ('');

CREATE STAGE IF NOT EXISTS CSV_STAGE
    FILE_FORMAT = CSV_STANDARD_FORMAT;

-- Raw columns intentionally remain VARCHAR to preserve source values and defer
-- parsing/cleansing to downstream models. SOURCE_FILE and LOADED_AT provide lineage.
CREATE TABLE IF NOT EXISTS RAW_SALES_TRANSACTIONS (
    TRANSACTION_ID VARCHAR,
    TRANSACTION_DATE VARCHAR,
    CUSTOMER_ID VARCHAR,
    PRODUCT_ID VARCHAR,
    QUANTITY VARCHAR,
    REVENUE VARCHAR,
    PRODUCT_COST VARCHAR,
    SHIPPING_COST VARCHAR,
    SOURCE_FILE VARCHAR,
    LOADED_AT TIMESTAMP_NTZ
);

CREATE TABLE IF NOT EXISTS RAW_CUSTOMERS (
    CUSTOMER_ID VARCHAR,
    CUSTOMER_NAME VARCHAR,
    COUNTRY VARCHAR,
    REGION VARCHAR,
    CUSTOMER_SINCE VARCHAR,
    CUSTOMER_STATUS VARCHAR,
    SOURCE_FILE VARCHAR,
    LOADED_AT TIMESTAMP_NTZ
);

CREATE TABLE IF NOT EXISTS RAW_PRODUCTS (
    PRODUCT_ID VARCHAR,
    PRODUCT_NAME VARCHAR,
    CATEGORY VARCHAR,
    PRODUCT_COST VARCHAR,
    SOURCE_FILE VARCHAR,
    LOADED_AT TIMESTAMP_NTZ
);

CREATE TABLE IF NOT EXISTS RAW_DATE_DIMENSION (
    SOURCE_DATE VARCHAR,
    MONTH_NAME VARCHAR,
    QUARTER VARCHAR,
    YEAR VARCHAR,
    SOURCE_FILE VARCHAR,
    LOADED_AT TIMESTAMP_NTZ
);

-- Each COPY is re-runnable: Snowflake tracks files already loaded into a table.
COPY INTO RAW_SALES_TRANSACTIONS (
    TRANSACTION_ID, TRANSACTION_DATE, CUSTOMER_ID, PRODUCT_ID,
    QUANTITY, REVENUE, PRODUCT_COST, SHIPPING_COST, SOURCE_FILE, LOADED_AT
)
FROM (
    SELECT $1, $2, $3, $4, $5, $6, $7, $8, METADATA$FILENAME, CURRENT_TIMESTAMP()::TIMESTAMP_NTZ
    FROM @CSV_STAGE
)
FILES = ('sales_transactions.csv')
FILE_FORMAT = (FORMAT_NAME = CSV_STANDARD_FORMAT)
ON_ERROR = 'ABORT_STATEMENT';

COPY INTO RAW_CUSTOMERS (
    CUSTOMER_ID, CUSTOMER_NAME, COUNTRY, REGION,
    CUSTOMER_SINCE, CUSTOMER_STATUS, SOURCE_FILE, LOADED_AT
)
FROM (
    SELECT $1, $2, $3, $4, $5, $6, METADATA$FILENAME, CURRENT_TIMESTAMP()::TIMESTAMP_NTZ
    FROM @CSV_STAGE
)
FILES = ('customers.csv')
FILE_FORMAT = (FORMAT_NAME = CSV_STANDARD_FORMAT)
ON_ERROR = 'ABORT_STATEMENT';

COPY INTO RAW_PRODUCTS (
    PRODUCT_ID, PRODUCT_NAME, CATEGORY, PRODUCT_COST, SOURCE_FILE, LOADED_AT
)
FROM (
    SELECT $1, $2, $3, $4, METADATA$FILENAME, CURRENT_TIMESTAMP()::TIMESTAMP_NTZ
    FROM @CSV_STAGE
)
FILES = ('products.csv')
FILE_FORMAT = (FORMAT_NAME = CSV_STANDARD_FORMAT)
ON_ERROR = 'ABORT_STATEMENT';

COPY INTO RAW_DATE_DIMENSION (
    SOURCE_DATE, MONTH_NAME, QUARTER, YEAR, SOURCE_FILE, LOADED_AT
)
FROM (
    SELECT $1, $2, $3, $4, METADATA$FILENAME, CURRENT_TIMESTAMP()::TIMESTAMP_NTZ
    FROM @CSV_STAGE
)
FILES = ('metric mind date_dimension.csv')
FILE_FORMAT = (FORMAT_NAME = CSV_STANDARD_FORMAT)
ON_ERROR = 'ABORT_STATEMENT';

-- Quick row-count check after loading.
SELECT 'RAW_SALES_TRANSACTIONS' AS TABLE_NAME, COUNT(*) AS ROW_COUNT FROM RAW_SALES_TRANSACTIONS
UNION ALL
SELECT 'RAW_CUSTOMERS', COUNT(*) FROM RAW_CUSTOMERS
UNION ALL
SELECT 'RAW_PRODUCTS', COUNT(*) FROM RAW_PRODUCTS
UNION ALL
SELECT 'RAW_DATE_DIMENSION', COUNT(*) FROM RAW_DATE_DIMENSION;
