
-- MetricMind: Business Question Analysis
-- Source: NOVAMART_DB.DBT_LAYYANKI.MART_METRICMIND


-- 1. Which regions generate the most revenue?
SELECT
    REGION,
    SUM(REVENUE) AS TOTAL_REVENUE,
    SUM(PROFIT) AS TOTAL_PROFIT
FROM NOVAMART_DB.DBT_LAYYANKI.MART_METRICMIND
GROUP BY REGION
ORDER BY TOTAL_REVENUE DESC;


-- 2. Which product categories have the highest profit margin?
SELECT
    CATEGORY,
    ROUND(SUM(PROFIT), 2) AS TOTAL_PROFIT,
    ROUND(
        100 * SUM(PROFIT) / NULLIF(SUM(REVENUE), 0),
        2
    ) AS PROFIT_MARGIN_PERCENTAGE
FROM NOVAMART_DB.DBT_LAYYANKI.MART_METRICMIND
GROUP BY CATEGORY
ORDER BY PROFIT_MARGIN_PERCENTAGE DESC;


-- 3. Which quarter generated the most profit?
SELECT
    YEAR,
    QUARTER,
    ROUND(SUM(PROFIT), 2) AS TOTAL_PROFIT
FROM NOVAMART_DB.DBT_LAYYANKI.MART_METRICMIND
GROUP BY YEAR, QUARTER
ORDER BY TOTAL_PROFIT DESC;
